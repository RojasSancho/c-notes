#include <stdio.h>

int main(void)
{
	// ===============================
	// FOR LOOP EXAMPLE
	// ===============================
	// Guide challenge solution
	// - Write a loop that print the numbers from 1 to 10 in ascendant order
	for (int number = 1; number <= 10; number++) {
		printf("%d - ", number);
	}
	printf("\n");
	
	return 0;
}
